const esc = (value) =>
  String(value ?? '').replace(
    /[&<>"']/g,
    (char) =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&apos;',
      })[char]
  );
const number = (value) => new Intl.NumberFormat().format(Number(value) || 0);
const base = (title, userName, content, height = 210) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="720" height="${height}" viewBox="0 0 720 ${height}" role="img" aria-label="${esc(title)} for ${esc(userName)}"><title>${esc(title)} for ${esc(userName)}</title><desc>GitHub data snapshot generated by Markdown Shop.</desc><rect width="720" height="${height}" rx="18" fill="#0d1117"/><rect x="1" y="1" width="718" height="${height - 2}" rx="17" fill="none" stroke="#30363d"/><text x="28" y="38" fill="#f0f6fc" font-family="Arial,sans-serif" font-size="19" font-weight="700">${esc(title)}</text><text x="690" y="38" text-anchor="end" fill="#8b949e" font-family="Arial,sans-serif" font-size="13">@${esc(userName)}</text>${content}<text x="28" y="${height - 17}" fill="#8b949e" font-family="Arial,sans-serif" font-size="10">GitHub API snapshot · Markdown Shop</text></svg>`;
const tile = (x, label, value, width = 150, y = 65) =>
  `<rect x="${x}" y="${y}" width="${width}" height="66" rx="10" fill="#161b22" stroke="#30363d"/><text x="${x + 14}" y="${y + 25}" fill="#8b949e" font-family="Arial,sans-serif" font-size="11">${esc(label)}</text><text x="${x + 14}" y="${y + 51}" fill="#58a6ff" font-family="Arial,sans-serif" font-size="21" font-weight="700">${esc(value)}</text>`;
const observedStreaks = (events) => {
  const days = [
    ...new Set(
      events.map((event) =>
        new Date(event.created_at).toISOString().slice(0, 10)
      )
    ),
  ].sort();
  const daySet = new Set(days);
  let run = 0;
  let longest = 0;
  let previous = null;
  days.forEach((day) => {
    const date = new Date(day);
    if (previous && (previous - date) / 86400000 === 1) run += 1;
    else run = 1;
    longest = Math.max(longest, run);
    previous = date;
  });
  let current = 0;
  const cursor = new Date();
  let key = cursor.toISOString().slice(0, 10);
  if (!daySet.has(key)) {
    cursor.setDate(cursor.getDate() - 1);
    key = cursor.toISOString().slice(0, 10);
  }
  while (daySet.has(key) && current < 100) {
    current += 1;
    cursor.setDate(cursor.getDate() - 1);
    key = cursor.toISOString().slice(0, 10);
  }
  return [current, longest];
};
export const buildGithubSvg = (kind, data, userName, contributors = []) => {
  const profile = data?.profile || {};
  const repos = data?.repos || [];
  const events = data?.events || [];
  const stars = repos.reduce(
    (sum, repo) => sum + (repo.stargazers_count || 0),
    0
  );
  const forks = repos.reduce((sum, repo) => sum + (repo.forks_count || 0), 0);
  const pushes = events.filter((event) => event.type === 'PushEvent');
  const commits = pushes.reduce(
    (sum, event) => sum + (event.payload?.commits?.length || 0),
    0
  );
  const repo = repos.find((item) => item.name === 'markdown-shop') || repos[0];
  const labels = {
    stats: 'GitHub Stats',
    streak: 'Observed Activity Streak',
    trophies: 'Profile Milestones',
    badges: 'GitHub Badges',
    followers: 'GitHub Followers',
    commits: 'Recent Commit Activity',
    activity: 'Recent Public Activity',
    snake: 'Recent Activity Grid',
    repo: 'Repository Summary',
    contributors: 'Repository Contributors',
    metrics: 'GitHub Metrics',
    views: 'Profile Views',
  };
  const title = labels[kind] || 'GitHub Profile';
  if (kind === 'trophies') {
    const awards = [
      ['Repositories', profile.public_repos, '#f2cc60'],
      ['Followers', profile.followers, '#a371f7'],
      ['Stars earned', stars, '#f0883e'],
      ['Forks received', forks, '#58a6ff'],
    ];
    const cards = awards
      .map(([label, value, color], index) => {
        const x = 28 + index * 168;
        return `<rect x="${x}" y="66" width="150" height="132" rx="14" fill="#161b22" stroke="#30363d"/><path d="M${x + 75} 83l8 7 11 1-4 10 4 10-11 1-8 7-8-7-11-1 4-10-4-10 11-1z" fill="${color}"/><text x="${x + 75}" y="139" text-anchor="middle" fill="#f0f6fc" font-family="Arial,sans-serif" font-size="21" font-weight="700">${number(value)}</text><text x="${x + 75}" y="166" text-anchor="middle" fill="#8b949e" font-family="Arial,sans-serif" font-size="11">${esc(label)}</text><text x="${x + 75}" y="185" text-anchor="middle" fill="${color}" font-family="Arial,sans-serif" font-size="10">MILESTONE</text>`;
      })
      .join('');
    return base(title, userName, cards, 220);
  }
  if (kind === 'badges') {
    const badges = [
      ['PUBLIC REPOS', profile.public_repos, '#58a6ff'],
      ['STARS', stars, '#f2cc60'],
      ['FORKS', forks, '#a371f7'],
      [
        'OPEN ISSUES',
        repos.reduce((sum, item) => sum + (item.open_issues_count || 0), 0),
        '#3fb950',
      ],
    ];
    const rows = badges
      .map(([label, value, color], index) => {
        const y = 67 + index * 31;
        return `<rect x="28" y="${y}" width="664" height="24" rx="5" fill="#161b22" stroke="#30363d"/><path d="M43 ${y + 6}l5 4 5-4v11l-5-3-5 3z" fill="${color}"/><text x="64" y="${y + 16}" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="11" font-weight="700">${esc(label)}</text><text x="674" y="${y + 16}" text-anchor="end" fill="${color}" font-family="Arial,sans-serif" font-size="12" font-weight="700">${number(value)}</text>`;
      })
      .join('');
    return base(title, userName, rows, 225);
  }
  if (kind === 'streak') {
    const [current, longest] = observedStreaks(events);
    const flame =
      '<path d="M118 76c5 14-7 18-2 29 3 7 12 8 17 3 9-9-2-21-1-32 8 7 18 20 16 34-2 15-13 25-29 25-17 0-29-12-28-27 1-13 12-24 27-32z" fill="#f0883e"/><path d="M128 105c4 7 8 11 4 17-3 5-10 5-13 0-3-5 1-11 9-17z" fill="#f2cc60"/>';
    const content =
      flame +
      tile(203, 'Current observed streak', number(current) + ' days', 205, 76) +
      tile(430, 'Longest observed', number(longest) + ' days', 205, 76) +
      '<text x="28" y="169" fill="#8b949e" font-family="Arial,sans-serif" font-size="12">Recent public events only · not GitHub contribution calendar data</text>';
    return base(title, userName, content, 205);
  }
  if (kind === 'commits') {
    const counts = Array.from({ length: 14 }, () => 0);
    events.forEach((event) => {
      if (event.type !== 'PushEvent') return;
      const age = Math.floor(
        (Date.now() - new Date(event.created_at).getTime()) / 86400000
      );
      if (age >= 0 && age < 14)
        counts[13 - age] += event.payload?.commits?.length || 0;
    });
    const maxCount = Math.max(1, ...counts);
    const points = counts
      .map(
        (value, index) =>
          48 + index * 47 + ',' + (155 - (value / maxCount) * 75)
      )
      .join(' ');
    const bars = counts
      .map((value, index) => {
        const x = 42 + index * 47;
        const height = Math.max(2, (value / maxCount) * 76);
        return `<rect x="${x}" y="${155 - height}" width="25" height="${height}" rx="4" fill="#58a6ff" opacity="0.85"><title>${value} observed commits</title></rect>`;
      })
      .join('');
    const chart =
      '<path d="M42 157H682M42 80V157" stroke="#30363d" fill="none"/>' +
      bars +
      `<polyline points="${points}" fill="none" stroke="#3fb950" stroke-width="2"/>`;
    return base(
      title,
      userName,
      chart +
        '<text x="42" y="178" fill="#8b949e" font-family="Arial,sans-serif" font-size="11">Last 14 days · visible public push events only</text>',
      205
    );
  }
  if (kind === 'followers') {
    const initials = (userName || 'GH').slice(0, 2).toUpperCase();
    const content = `<circle cx="115" cy="108" r="42" fill="#1f6feb"/><text x="115" y="116" text-anchor="middle" fill="#ffffff" font-family="Arial,sans-serif" font-size="22" font-weight="700">${esc(initials)}</text><text x="182" y="103" fill="#f0f6fc" font-family="Arial,sans-serif" font-size="30" font-weight="700">${number(profile.followers)}</text><text x="184" y="128" fill="#8b949e" font-family="Arial,sans-serif" font-size="13">followers</text><path d="M183 145H450" stroke="#30363d"/><text x="183" y="166" fill="#58a6ff" font-family="Arial,sans-serif" font-size="12">Following ${number(profile.following)}</text>`;
    return base(title, userName, content, 205);
  }
  if (kind === 'views')
    return base(
      title,
      userName,
      '<text x="28" y="92" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="16">Profile view counts are not available from GitHub API.</text>',
      150
    );
  if (kind === 'repo') {
    const content = repo
      ? `<text x="28" y="82" fill="#58a6ff" font-family="Arial,sans-serif" font-size="17" font-weight="700">${esc(repo.full_name)}</text><text x="28" y="108" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="12">${esc(repo.description || 'GitHub repository')}</text>${tile(28, 'Stars', number(repo.stargazers_count), 150, 124)}${tile(194, 'Forks', number(repo.forks_count), 150, 124)}${tile(360, 'Open issues', number(repo.open_issues_count), 150, 124)}`
      : '<text x="28" y="90" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="14">No public repository data.</text>';
    return base(title, userName, content, 220);
  }
  if (kind === 'contributors') {
    const rows = contributors
      .slice(0, 8)
      .map(
        (person, index) =>
          `<circle cx="${48 + (index % 4) * 166}" cy="${83 + Math.floor(index / 4) * 48}" r="5" fill="#3fb950"/><text x="${61 + (index % 4) * 166}" y="${88 + Math.floor(index / 4) * 48}" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="12">${esc(person.login)} · ${number(person.contributions)}</text>`
      )
      .join('');
    return base(
      title,
      userName,
      rows ||
        '<text x="28" y="90" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="14">No contributor data.</text>',
      190
    );
  }
  if (kind === 'activity' || kind === 'snake') {
    const byDay = new Map();
    events.forEach((event) => {
      const day = new Date(event.created_at).toISOString().slice(0, 10);
      byDay.set(day, (byDay.get(day) || 0) + 1);
    });
    const cells = Array.from({ length: 91 }, (_, index) => {
      const date = new Date();
      date.setDate(date.getDate() - (90 - index));
      const day = date.toISOString().slice(0, 10);
      const count = byDay.get(day) || 0;
      const x = 28 + (index % 13) * 21;
      const y = 68 + Math.floor(index / 13) * 18;
      return `<rect x="${x}" y="${y}" width="15" height="12" rx="3" fill="${count ? '#3fb950' : '#21262d'}" opacity="${count ? Math.min(1, 0.45 + count * 0.13) : 1}"><title>${day}: ${count} events</title></rect>`;
    }).join('');
    return base(
      title,
      userName,
      cells +
        '<text x="330" y="95" fill="#8b949e" font-family="Arial,sans-serif" font-size="13">Recent public events only · not a full contribution calendar</text>',
      220
    );
  }
  if (kind === 'streak' || kind === 'commits') {
    const [current, longest] = observedStreaks(events);
    const metrics =
      kind === 'streak'
        ? tile(28, 'Observed current streak', number(current) + ' days', 200) +
          tile(246, 'Longest observed streak', number(longest) + ' days', 200)
        : tile(28, 'Public events', number(events.length), 150) +
          tile(194, 'Push events', number(pushes.length), 150) +
          tile(360, 'Commits in visible pushes', number(commits), 200);
    const note =
      '<text x="28" y="165" fill="#8b949e" font-family="Arial,sans-serif" font-size="12">Limited recent public event feed; not total contribution counts.</text>';
    return base(title, userName, metrics + note, 205);
  }
  const stats =
    kind === 'followers'
      ? [['Followers', profile.followers]]
      : kind === 'trophies'
        ? [
            ['Repositories', profile.public_repos],
            ['Followers', profile.followers],
            ['Stars', stars],
            ['Forks', forks],
          ]
        : kind === 'badges'
          ? [
              ['Repositories', profile.public_repos],
              ['Stars', stars],
              ['Forks', forks],
              [
                'Open issues',
                repos.reduce(
                  (sum, item) => sum + (item.open_issues_count || 0),
                  0
                ),
              ],
            ]
          : [
              ['Repositories', profile.public_repos],
              ['Followers', profile.followers],
              ['Following', profile.following],
              ['Gists', profile.public_gists],
            ];
  const content = stats
    .map(([label, value], index) =>
      tile(28 + index * 166, label, number(value))
    )
    .join('');
  if (kind !== 'stats') return base(title, userName, content, 165);
  const languages = repos.reduce((counts, item) => {
    if (item.language) counts[item.language] = (counts[item.language] || 0) + 1;
    return counts;
  }, {});
  const top = Object.entries(languages)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5);
  const max = Math.max(1, top[0]?.[1] || 1);
  const bars = top
    .map(([language, count], index) => {
      const y = 164 + index * 23;
      return `<text x="28" y="${y + 11}" fill="#c9d1d9" font-family="Arial,sans-serif" font-size="11">${esc(language)}</text><rect x="130" y="${y}" width="420" height="14" rx="5" fill="#21262d"/><rect x="130" y="${y}" width="${Math.max(4, (420 * count) / max)}" height="14" rx="5" fill="#58a6ff"/><text x="565" y="${y + 11}" fill="#8b949e" font-family="Arial,sans-serif" font-size="11">${count} repos</text>`;
    })
    .join('');
  return base(
    title,
    userName,
    content +
      '<text x="28" y="157" fill="#8b949e" font-family="Arial,sans-serif" font-size="11">Primary language by visible repository count (not code volume)</text>' +
      bars,
    164 + top.length * 23 + 24
  );
};
